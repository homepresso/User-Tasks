--
-- Storage buckets/policies and Realtime publication membership: both live
-- outside the public schema, so the baseline dump does not capture them.
-- Mirrors production as of 2026-10-15 (storage.buckets rows and storage
-- schema dump), with one deliberate tightening noted below.
-- ============================================================================

-- Storage exists only on Supabase: elsewhere (plain Postgres + the storage
-- provider) the buckets and policies below are skipped. Same statements as
-- before inside the guard, so Supabase databases get exactly what they did.
do $storage$
begin
  if to_regclass('storage.objects') is null or to_regclass('storage.buckets') is null then
    raise notice 'storage schema not found; skipping buckets and storage policies';
    return;
  end if;

  -- ── Buckets ────────────────────────────────────────────────────────────────
  -- task-files: data-table/integration uploads, Office files generated by the
  --   workflow engine (workflow-files/{tenantId}/…). Public: the app stores
  --   getPublicUrl() links.
  -- logos: tenant branding logos (components/settings/logo-upload.tsx).
  insert into storage.buckets (id, name, public)
  values ('task-files', 'task-files', true),
         ('logos', 'logos', true)
  on conflict (id) do nothing;

  -- ── task-files policies ────────────────────────────────────────────────────
  -- Production's policies had no role restriction (anon could upload/delete).
  -- Browser uploads always carry a signed-in session and server code uses the
  -- service role (which bypasses RLS), so writes are scoped to `authenticated`.
  -- 20261015000004_strip_back.sql applies the same tightening to databases
  -- created before this baseline.
  drop policy if exists "task_files_select" on storage.objects;
  create policy "task_files_select" on storage.objects
    for select using (bucket_id = 'task-files');

  drop policy if exists "task_files_upload" on storage.objects;
  create policy "task_files_upload" on storage.objects
    for insert to authenticated with check (bucket_id = 'task-files');

  drop policy if exists "task_files_delete" on storage.objects;
  create policy "task_files_delete" on storage.objects
    for delete to authenticated using (bucket_id = 'task-files');

  -- ── logos policies (as in production) ──────────────────────────────────────
  drop policy if exists "Public logo access" on storage.objects;
  create policy "Public logo access" on storage.objects
    for select using (bucket_id = 'logos');

  drop policy if exists "Users can upload logos" on storage.objects;
  create policy "Users can upload logos" on storage.objects
    for insert with check (bucket_id = 'logos' and auth.uid() is not null);

  drop policy if exists "Users can update logos" on storage.objects;
  create policy "Users can update logos" on storage.objects
    for update using (bucket_id = 'logos' and auth.uid() is not null);

  drop policy if exists "Users can delete logos" on storage.objects;
  create policy "Users can delete logos" on storage.objects
    for delete using (bucket_id = 'logos' and auth.uid() is not null);
end $storage$;

-- ── Realtime ───────────────────────────────────────────────────────────────
-- Tables the client subscribes to with postgres_changes: task lists/queue/
-- detail (hooks/use-tasks, use-task-queue, use-assigned-tasks,
-- use-task-realtime), notifications, and the Live Logs viewer
-- (hooks/use-live-logs.ts).
do $$
declare
  tbl text;
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    raise notice 'supabase_realtime publication not found; skipping realtime setup';
    return;
  end if;
  foreach tbl in array array[
    'tasks', 'task_assignees', 'notifications', 'lifecycle_events',
    'workflow_logs', 'object_audit_log', 'integration_call_logs', 'agent_runs'
  ] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = tbl
    ) then
      execute format('alter publication supabase_realtime add table public.%I', tbl);
    end if;
  end loop;
end $$;
