-- Run checkpoints, step idempotency and queued hand-offs (Phase 1 of the
-- processing tier; core, open source).
--
-- * workflow_runs.checkpoint: the running segment of a run (how it started or
--   resumed, plus the steps completed since — output and variable changes —
--   and the side-effecting steps started). Written after each step by
--   checkpoint_run_step; a run whose worker was lost resumes after the last
--   completed step instead of repeating side effects (lib/workflow-checkpoints.ts).
--   Cleared when the run pauses or finishes.
-- * checkpoint_run_step(run, segment, completed, started): merges one step
--   into the checkpoint of the given segment (no-op for another segment).
-- * workflow_step_effects: side effects already performed, by idempotency key
--   (`<run>:<node>:<visit>`): a re-run of an email / data-table step after a
--   lost worker finds its effect and does not repeat it. Service role only;
--   purge_step_effects(before) deletes old rows (daily log cleanup).
-- * recover_expired_jobs: a stuck resume job whose run was already running is
--   requeued like any other job (instead of dead): the processor resumes the
--   run from its checkpoint, or fails it as interrupted when it has none.
-- * complete_leased_job keeps the run's HTTP `response` (middleware
--   workflows, capped at 4 MB) in the job result, for a web app waiting on a
--   queued request/response run.
-- * processing_notify(kind): NOTIFY usertasks_processing, '<kind>' — the
--   wake-up a processing provider sends its workers for agent / media work
--   (workflow jobs already NOTIFY workflow_queue on enqueue). Service role only.
-- * workflow_run_event_relay: the engine events of a queued designer test run
--   (written by the worker, streamed to the designer by the web app, deleted
--   when streamed; purge_run_event_relay(before) for leftovers).
--
-- Plain SQL, no pg_cron. Additive and idempotent. Needs 20270124090000.

ALTER TABLE public.workflow_runs ADD COLUMN IF NOT EXISTS checkpoint jsonb;

-- ── checkpoint_run_step ─────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.checkpoint_run_step(
  p_run_id uuid,
  p_segment text,
  p_completed jsonb DEFAULT NULL,
  p_started jsonb DEFAULT NULL
) RETURNS boolean
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
  v_count integer;
BEGIN
  UPDATE workflow_runs SET checkpoint = jsonb_set(
      jsonb_set(
        checkpoint,
        '{completed}',
        coalesce(checkpoint->'completed', '{}'::jsonb) || coalesce(p_completed, '{}'::jsonb)
      ),
      '{started}',
      coalesce(checkpoint->'started', '{}'::jsonb) || coalesce(p_started, '{}'::jsonb)
    )
  WHERE id = p_run_id
    AND status = 'running'
    AND checkpoint->>'segment' = p_segment;
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count > 0;
END;
$$;

-- ── workflow_step_effects ───────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.workflow_step_effects (
  key text PRIMARY KEY CHECK (char_length(key) BETWEEN 1 AND 300),
  tenant_id uuid NOT NULL,
  run_id uuid,
  node_id text,
  kind text NOT NULL,
  result jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_workflow_step_effects_created ON public.workflow_step_effects (created_at);
ALTER TABLE public.workflow_step_effects ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.workflow_step_effects FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.workflow_step_effects TO service_role;

CREATE OR REPLACE FUNCTION public.purge_step_effects(p_before timestamptz, p_batch_size integer DEFAULT 5000)
  RETURNS integer
    LANGUAGE plpgsql
    SET search_path TO ''
    AS $$
DECLARE
  v_count integer;
BEGIN
  DELETE FROM public.workflow_step_effects e
  WHERE e.key IN (
    SELECT key FROM public.workflow_step_effects
    WHERE created_at < p_before
    LIMIT greatest(1, least(coalesce(p_batch_size, 5000), 50000))
  );
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

