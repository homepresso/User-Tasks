/**
 * Install profile: the customer's infrastructure choices in one document,
 * shared by the installers (one-line Docker installer, the Windows .msi) and
 * the in-browser setup wizard, so none of them invents its own mapping.
 *
 *   profile (JSON / flags)  →  validateProfile()  →  profileToConfig()  →  env vars + instance settings
 *                                                 →  checkProfile() (lib/install/checks.ts, server only)
 *
 * The provider ids and option names are exactly the ones lib/config uses
 * (PROVIDER_IDS, `<area>.<option>` instance settings, `usertasks-admin switch
 * --set <option>=…`), and every provider option is validated with the same
 * field schemas as Settings → Infrastructure (lib/config/provider-forms), so
 * the profile stays in step with the providers without a second list.
 *
 * Pure (no node: imports): the wizard's client components import the presets
 * and labels. The contract is documented in docs/install-profile.md.
 */

export const PROFILE_VERSION = 1

