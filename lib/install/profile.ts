const OPTION_NAME = /^[a-z][a-z0-9_]{0,62}$/
const scalar = z.union([z.string(), z.number(), z.boolean()]).transform((v) => String(v))
const optionsSchema = z.record(z.string().regex(OPTION_NAME, 'option names are lowercase letters, digits and _'), scalar).default({})
const emailAddress = z.string().trim().toLowerCase().regex(/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/, 'must be an email address')
const httpUrl = z.string().trim().url().refine((v) => /^https?:\/\//i.test(v), 'must start with http:// or https://')
const optionalText = z.string().trim().min(1).optional()

export const AppSchema = z.object({
  /** The address people open (no trailing slash). */
  url: httpUrl.transform((v) => v.replace(/\/+$/, '')),
  /** Port the app listens on (bundled installs). */
  port: z.coerce.number().int().min(1).max(65535).optional(),
  /** Instance administrators (Settings → Infrastructure, the setup wizard after setup). */
  adminEmails: z.array(emailAddress).default([]),
  /** First-run /setup code (8+ characters). Generated by `write --generate-secrets` when absent. */
  setupCode: z.string().trim().min(8).max(64).optional(),
  /** 32 bytes as 64 hex or 44 base64 characters, or a secret:// reference. Never regenerated once set. */
  encryptionKey: z.string().trim().refine(validEncryptionKey, 'must be 32 bytes as 64 hex or 44 base64 characters, or a secret:// reference').optional(),
  cronSecret: z.string().trim().min(16).optional(),
  signingSecret: z.string().trim().min(16).optional(),
  instanceAdminToken: z.string().trim().min(16).optional(),
}).strict()

/** A Supabase project (database, auth, files or live updates on Supabase). */
export const SupabaseSchema = z.object({
  url: httpUrl.transform((v) => v.replace(/\/+$/, '')),
  anonKey: z.string().trim().min(1),
  serviceRoleKey: z.string().trim().min(1),
  jwtSecret: optionalText,
}).strict()

export const POSTGRES_HOSTING = ['bundled', 'own', 'rds', 'azure', 'cloudsql'] as const
export const POSTGRES_AUTH = ['password', 'azure', 'gcp', 'aws'] as const
export const POSTGRES_SSLMODES = ['disable', 'require', 'verify-full'] as const

const DatabaseSupabaseSchema = z.object({
  provider: z.literal('supabase'),
  /** Optional direct connection (Session pooler) for usertasks-admin and data switches later. */
  url: optionalText,
}).strict()

const DatabasePostgresSchema = z.object({
  provider: z.literal('postgres'),
  /** bundled: installed with UserTasks · own: your server · rds / azure / cloudsql: a managed service. */
  hosting: z.enum(POSTGRES_HOSTING).default('own'),
  /** Full connection string (or host / database / user below). */
  url: optionalText,
  host: optionalText,
  port: z.coerce.number().int().min(1).max(65535).optional(),
  database: optionalText,
  user: optionalText,
  password: optionalText,
  sslmode: z.enum(POSTGRES_SSLMODES).optional(),
  /** CA certificate file on the server (verify-full against a private CA). */
  caFile: optionalText,
  /** password, or a token: azure (Entra ID), gcp (Cloud SQL IAM), aws (RDS IAM). */
  auth: z.enum(POSTGRES_AUTH).default('password'),
  awsRegion: optionalText,
  /** Session connection for migrations, live updates and the scheduler lock when `url` goes through a transaction pooler. */
  sessionUrl: optionalText,
}).strict()

export const DatabaseSchema = z.discriminatedUnion('provider', [DatabaseSupabaseSchema, DatabasePostgresSchema])

/** Directory (LDAP / Active Directory) sign-in and sync: set up per workspace after setup. */
export const LdapSchema = z.object({
  url: z.string().trim().regex(/^ldaps?:\/\/[^\s/]+(:\d+)?\/?$/i, 'must be ldap://host[:port] or ldaps://host[:port]'),
  bindDn: z.string().trim().min(1),
  bindPassword: optionalText,
  baseDn: z.string().trim().min(1),
  startTls: z.boolean().default(false),
  caFile: optionalText,
  /** People sign in with their directory password. */
  passwordLogin: z.boolean().default(false),
}).strict()

const providerBlock = <A extends ProviderArea>(area: A) => z.object({
  provider: z.enum(PROVIDER_IDS[area] as unknown as [string, ...string[]]),
  options: optionsSchema,
}).strict()

export const SMTP_PRESETS = ['generic', 'm365', 'exchange', 'gmail', 'mailpit'] as const

export const AuthSchema = z.object({
  provider: z.enum(PROVIDER_IDS.auth as unknown as [string, ...string[]]),
  /** Identity providers (OIDC / SAML), exactly as auth.sso_providers takes them. */
  sso: z.array(SsoIdpSchema).default([]),
  options: optionsSchema,
  ldap: LdapSchema.optional(),
}).strict()

export const EmailSchema = providerBlock('email').extend({
  /** smtp only: fill host / port / TLS for a known service (values given win). */
  smtpPreset: z.enum(SMTP_PRESETS).optional(),
}).strict()

export const ProfileSchema = z.object({
  version: z.literal(PROFILE_VERSION).default(PROFILE_VERSION),
  /** The preset this profile started from (informational). */
  preset: z.string().optional(),
  /** env: everything in the environment · settings: changeable areas in instance_settings (the wizard can change them). */
  placement: z.enum(['env', 'settings']).default('env'),
  app: AppSchema,
  supabase: SupabaseSchema.optional(),
  database: DatabaseSchema,
  auth: AuthSchema,
  storage: providerBlock('storage'),
  email: EmailSchema,
  scheduler: providerBlock('scheduler'),
  realtime: providerBlock('realtime'),
  cache: providerBlock('cache').default({ provider: 'memory', options: {} }),
  secrets: providerBlock('secrets').default({ provider: 'env', options: {} }),
  kms: providerBlock('kms').default({ provider: 'env', options: {} }),
}).strict()

