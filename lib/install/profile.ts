// ── Building a profile from layers ──────────────────────────────────────────

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

/** Deep merge (later layers win; arrays are replaced, not merged). A provider change drops the earlier provider's options. */
export function mergeProfileLayers(...layers: Array<Record<string, unknown> | undefined>): Record<string, unknown> {
  const out: Record<string, unknown> = {}
  for (const layer of layers) {
    if (!layer) continue
    for (const [key, value] of Object.entries(layer)) {
      const current = out[key]
      if (isPlainObject(value) && isPlainObject(current)) {
        const providerChanged = typeof value.provider === 'string' && typeof current.provider === 'string' && value.provider !== current.provider
        out[key] = providerChanged ? mergeProfileLayers(value) : mergeProfileLayers(current, value)
      } else {
        out[key] = value
      }
    }
  }
  return out
}

/**
 * `--set <path>=<value>` and `--provider <area>=<id>` as a layer. Paths:
 * app.url, database.url, supabase.anonKey, email.options.smtp_host (or the
 * short form email.smtp_host: anything that isn't a section field is an
 * option), files.local_root (alias of storage), auth.sso (JSON array).
 */
export function flagsLayer(sets: Record<string, string>, providers: Record<string, string> = {}): Record<string, unknown> {
  const layer: Record<string, unknown> = {}
  const section = (name: string): Record<string, unknown> => {
    const existing = layer[name]
    if (isPlainObject(existing)) return existing
    const created: Record<string, unknown> = {}
    layer[name] = created
    return created
  }
  for (const [rawArea, id] of Object.entries(providers)) {
    const area = PROFILE_AREA_ALIASES[rawArea] ?? rawArea
    if (!(PROFILE_AREAS as readonly string[]).includes(area)) throw new ProfileInputError(`--provider: unknown area "${rawArea}" (${PROFILE_AREAS.join(', ')})`)
    section(area).provider = id.trim().toLowerCase()
  }
  for (const [path, raw] of Object.entries(sets)) {
    const parts = path.split('.')
    const head: string = PROFILE_AREA_ALIASES[parts[0]] ?? parts[0]
    if (head === 'placement' || head === 'preset') { layer[head] = raw; continue }
    if (parts.length < 2) throw new ProfileInputError(`--set ${path}: use <section>.<field>=<value> (e.g. app.url=https://tasks.example.com)`)
    if (head === 'app' || head === 'supabase') {
      const field = parts.slice(1).join('.')
      section(head)[field] = head === 'app' && field === 'adminEmails' ? raw.split(/[\s,;]+/).filter(Boolean) : coerceScalar(field, raw)
      continue
    }
    if (!(PROFILE_AREAS as readonly string[]).includes(head)) throw new ProfileInputError(`--set ${path}: unknown section "${parts[0]}"`)
    const target = section(head)
    const fieldNames = SECTION_FIELDS[head as ProfileArea]
    if (parts[1] === 'options' && parts.length === 3) {
      target.options = { ...(isPlainObject(target.options) ? target.options : {}), [parts[2]]: raw }
    } else if (parts.length === 2 && fieldNames.includes(parts[1])) {
      target[parts[1]] = parts[1] === 'sso' || parts[1] === 'ldap' ? parseJson(path, raw) : coerceScalar(parts[1], raw)
    } else if (parts.length === 2 && head !== 'database') {
      target.options = { ...(isPlainObject(target.options) ? target.options : {}), [parts[1]]: raw }
    } else {
      throw new ProfileInputError(`--set ${path}: unknown field (${fieldNames.join(', ')}${head === 'database' ? '' : ', or an option name'})`)
    }
  }
  return layer
}

const SECTION_FIELDS: Record<ProfileArea, string[]> = {
  database: ['provider', 'hosting', 'url', 'host', 'port', 'database', 'user', 'password', 'sslmode', 'caFile', 'auth', 'awsRegion', 'sessionUrl'],
  auth: ['provider', 'sso', 'ldap'],
  storage: ['provider'],
  email: ['provider', 'smtpPreset'],
  scheduler: ['provider'],
  realtime: ['provider'],
  cache: ['provider'],
  secrets: ['provider'],
  kms: ['provider'],
}

function coerceScalar(field: string, raw: string): unknown {
  if (field === 'port') return Number(raw)
  return raw
}

function parseJson(path: string, raw: string): unknown {
  try {
    return JSON.parse(raw)
  } catch {
    throw new ProfileInputError(`--set ${path}: expected JSON`)
  }
}

export class ProfileInputError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'ProfileInputError'
  }
}

// ── Validation ──────────────────────────────────────────────────────────────

export interface ProfileIssue {
  /** Dotted path in the profile (e.g. email.options.smtp_host). */
  path: string
  message: string
}

export type ValidationResult =
  | { ok: true; profile: Profile; warnings: ProfileIssue[] }
  | { ok: false; errors: ProfileIssue[]; warnings: ProfileIssue[] }

const SECRET_REF = /^secret:\/\/[A-Za-z0-9_./#%-]{1,200}$/

function validEncryptionKey(value: string): boolean {
  const v = value.trim()
  if (SECRET_REF.test(v)) return true
  if (/^[0-9a-f]{64}$/i.test(v)) return true
  return /^[A-Za-z0-9+/]{43}=$/.test(v)
}

/** Every provider option of an area block, checked with the provider's form fields. */
function checkOptions(area: ProfileArea, provider: string, options: Record<string, string>, errors: ProfileIssue[], warnings: ProfileIssue[]): void {
  const providerArea = PROFILE_AREA_TO_PROVIDER[area]
  const fields = new Map<string, ProviderField>(providerFields(providerArea, provider).map((f) => [f.option, f]))
  for (const [option, value] of Object.entries(options)) {
    const field = fields.get(option)
    if (!field) {
      errors.push({ path: `${area}.options.${option}`, message: fields.size ? `not an option of the ${provider} provider (${[...fields.keys()].join(', ')})` : `the ${provider} provider has no options` })
      continue
    }
    if (area === 'auth' && option === 'sso_providers') {
      errors.push({ path: `${area}.options.${option}`, message: 'use auth.sso (a list of identity providers) instead' })
      continue
    }
    const parsed = parseFieldValue(field, value)
    if (!parsed.ok) errors.push({ path: `${area}.options.${option}`, message: parsed.error })
  }
  for (const field of fields.values()) {
    if (field.required && !(field.option in options)) errors.push({ path: `${area}.options.${field.option}`, message: `${field.label} is required by the ${provider} provider` })
  }
  void warnings
}

function zodIssues(error: z.ZodError): ProfileIssue[] {
  return error.issues.map((issue) => ({ path: issue.path.join('.') || '(profile)', message: issue.message }))
}

/** Validate a profile (after merging layers). Never throws. */
export function validateProfile(input: unknown): ValidationResult {
  const warnings: ProfileIssue[] = []
  const parsed = ProfileSchema.safeParse(input)
  if (!parsed.success) return { ok: false, errors: zodIssues(parsed.error), warnings }
  const profile = applySmtpPreset(parsed.data)
  const errors: ProfileIssue[] = []

  // Supabase is needed by anything on Supabase.
  const onSupabase = supabaseAreas(profile)
  if (onSupabase.length && !profile.supabase) {
    errors.push({ path: 'supabase', message: `a Supabase project (url, anonKey, serviceRoleKey) is needed by: ${onSupabase.map((a) => PROFILE_AREA_LABELS[a].toLowerCase()).join(', ')}` })
  }
  if (!onSupabase.length && profile.supabase) warnings.push({ path: 'supabase', message: 'given but nothing uses Supabase: it is ignored' })
  if (profile.database.provider === 'postgres' && profile.auth.provider === 'supabase') {
    errors.push({ path: 'auth.provider', message: 'Supabase sign-in needs the Supabase database: use built-in sign-in (with SSO if you like) on your own PostgreSQL' })
  }
  if (profile.database.provider === 'postgres' && profile.scheduler.provider === 'pg_cron') {
    warnings.push({ path: 'scheduler.provider', message: 'pg_cron needs the pg_cron and pg_net extensions in your PostgreSQL; the built-in worker needs nothing extra' })
  }

  // Database.
  const db = profile.database
  if (db.provider === 'postgres') {
    if (!db.url && !(db.host && db.database && db.user)) {
      errors.push({ path: 'database.url', message: 'give a connection string (url), or host, database and user' })
    }
    if (db.url && !/^postgres(ql)?:\/\//i.test(db.url)) errors.push({ path: 'database.url', message: 'must start with postgres:// or postgresql://' })
    if (db.sessionUrl && !/^postgres(ql)?:\/\//i.test(db.sessionUrl)) errors.push({ path: 'database.sessionUrl', message: 'must start with postgres:// or postgresql://' })
    const managedAuth: Partial<Record<(typeof POSTGRES_HOSTING)[number], string>> = { rds: 'aws', azure: 'azure', cloudsql: 'gcp' }
    if (db.auth !== 'password' && managedAuth[db.hosting] && managedAuth[db.hosting] !== db.auth) {
      errors.push({ path: 'database.auth', message: `${db.auth} token sign-in does not work with ${db.hosting} (use password${managedAuth[db.hosting] ? ` or ${managedAuth[db.hosting]}` : ''})` })
    }
    if (db.auth !== 'password' && (db.hosting === 'bundled' || db.hosting === 'own')) {
      errors.push({ path: 'database.auth', message: 'token sign-in (azure, gcp, aws) is for managed databases only: use password' })
    }
    if (db.auth === 'password' && !db.url && !db.password && db.hosting !== 'bundled') {
      warnings.push({ path: 'database.password', message: 'no password: the server must trust this connection (pg_hba trust / peer) — fine locally, not across a network' })
    }
    if (db.auth !== 'password' && db.password) warnings.push({ path: 'database.password', message: `ignored with ${db.auth} token sign-in` })
    if (['rds', 'azure', 'cloudsql'].includes(db.hosting) && (db.sslmode ?? sslmodeOf(db.url)) === 'disable') {
      errors.push({ path: 'database.sslmode', message: 'managed databases need TLS: use require or verify-full' })
    }
    if (db.sslmode === 'verify-full' && db.hosting === 'own' && !db.caFile) {
      warnings.push({ path: 'database.caFile', message: 'verify-full against a private certificate authority needs its CA file' })
    }
  }

  // Sign-in.
  const auth = profile.auth
  if (auth.provider === 'supabase' && auth.sso.length) {
    errors.push({ path: 'auth.sso', message: 'with Supabase sign-in, set up SSO in the Supabase dashboard; identity providers here need built-in sign-in' })
  }
  if ((auth.provider === 'oidc' || auth.provider === 'saml') && !auth.sso.some((idp) => idp.type === auth.provider)) {
    errors.push({ path: 'auth.sso', message: `${auth.provider.toUpperCase()}-only sign-in needs at least one ${auth.provider.toUpperCase()} identity provider in auth.sso` })
  }
  const ids = new Set<string>()
  auth.sso.forEach((idp, i) => {
    if (ids.has(idp.id)) errors.push({ path: `auth.sso.${i}.id`, message: `duplicate identity provider id "${idp.id}"` })
    ids.add(idp.id)
    if (idp.type === 'oidc') {
      if (idp.preset === 'entra' && !idp.tenantId) errors.push({ path: `auth.sso.${i}.tenantId`, message: 'Entra ID needs the directory (tenant) id' })
      if ((idp.preset === 'keycloak') && !(idp.baseUrl && idp.realm) && !idp.issuer) errors.push({ path: `auth.sso.${i}.baseUrl`, message: 'Keycloak needs baseUrl and realm (or issuer)' })
      if ((idp.preset === 'okta' || idp.preset === 'auth0') && !idp.domain && !idp.issuer) errors.push({ path: `auth.sso.${i}.domain`, message: `${idp.preset} needs its domain (or issuer)` })
      if (idp.preset === 'adfs' && !idp.baseUrl && !idp.issuer) errors.push({ path: `auth.sso.${i}.baseUrl`, message: 'AD FS needs baseUrl (https://adfs.example.com) or issuer' })
      if (idp.preset === 'generic' && !idp.issuer && !idp.discoveryUrl) errors.push({ path: `auth.sso.${i}.issuer`, message: 'a generic OIDC provider needs issuer (or discoveryUrl)' })
    } else if (!idp.metadataUrl && !idp.metadataXml && !(idp.entryPoint && idp.idpCert)) {
      errors.push({ path: `auth.sso.${i}.metadataUrl`, message: 'SAML needs the IdP metadata (metadataUrl or metadataXml), or entryPoint and idpCert' })
    }
  })
  if (auth.ldap && auth.provider !== 'builtin') {
    errors.push({ path: 'auth.ldap', message: 'directory (LDAP) password sign-in works with built-in sign-in only' })
  }
  if (auth.ldap && /^ldap:/i.test(auth.ldap.url) && !auth.ldap.startTls) {
    warnings.push({ path: 'auth.ldap.url', message: 'plain ldap:// sends passwords unencrypted: use ldaps:// or startTls' })
  }

  // Provider options (form field schemas, required fields).
  for (const area of PROFILE_AREAS) {
    if (area === 'database') continue
    const block = profile[area] as { provider: string; options: Record<string, string> }
    checkOptions(area, block.provider, block.options, errors, warnings)
  }
  if (profile.email.provider !== 'resend' && profile.email.provider !== 'console' && !profile.email.options.from) {
    errors.push({ path: 'email.options.from', message: `a from address is required by the ${profile.email.provider} provider` })
  }
  if (profile.email.provider === 'console') warnings.push({ path: 'email.provider', message: 'console only logs messages: nobody receives invitations or password resets until you set up real email' })
  if (profile.email.provider === 'smtp' && profile.email.smtpPreset === 'm365' && !profile.email.options.smtp_user) {
    errors.push({ path: 'email.options.smtp_user', message: 'Microsoft 365 needs the mailbox user name (and its password or an app password)' })
  }
  if (profile.realtime.provider === 'supabase' && profile.database.provider !== 'supabase') {
    errors.push({ path: 'realtime.provider', message: 'Supabase live updates need the Supabase database: use sse' })
  }
  if (profile.scheduler.provider === 'worker' && /^(0|false|off|no)$/i.test(profile.scheduler.options.in_process ?? '')) {
    warnings.push({ path: 'scheduler.options.in_process', message: 'off: run a dedicated worker process (`usertasks worker`), or background jobs never run' })
  }
  if (!profile.app.adminEmails.length) {
    warnings.push({ path: 'app.adminEmails', message: 'no instance admins yet: the account created on /setup becomes one' })
  }
  if (/^http:\/\//i.test(profile.app.url) && !/^http:\/\/(localhost|127\.|\[::1\])/i.test(profile.app.url)) {
    warnings.push({ path: 'app.url', message: 'plain http on a network address: sign-in cookies travel unencrypted; put HTTPS in front' })
  }
  if (profile.placement === 'env') {
    warnings.push({ path: 'placement', message: 'env: the setup wizard shows these services but cannot change them (values set in the environment win); use placement "settings" to keep them changeable' })
  }
  return errors.length ? { ok: false, errors, warnings } : { ok: true, profile, warnings }
}

function sslmodeOf(url: string | undefined): string | undefined {
  if (!url) return undefined
  return /[?&]sslmode=([^&]+)/.exec(url)?.[1]
}

/** Areas on Supabase. */
export function supabaseAreas(profile: Profile): ProfileArea[] {
  const out: ProfileArea[] = []
  if (profile.database.provider === 'supabase') out.push('database')
  if (profile.auth.provider === 'supabase') out.push('auth')
  if (profile.storage.provider === 'supabase') out.push('storage')
  if (profile.realtime.provider === 'supabase') out.push('realtime')
  if (profile.secrets.provider === 'supabase_vault') out.push('secrets')
  return out
}

function applySmtpPreset(profile: Profile): Profile {
  if (profile.email.provider !== 'smtp' || !profile.email.smtpPreset) return profile
  return { ...profile, email: { ...profile.email, options: { ...SMTP_PRESET_OPTIONS[profile.email.smtpPreset], ...profile.email.options } } }
}

// ── Mapping to configuration ────────────────────────────────────────────────

export interface ConfigSetting {
  key: string
  value: string
  /** Stored encrypted (credentials). */
  secret: boolean
}

export interface ProfileConfig {
  /** Environment variables (an env file or a Windows service environment). */
  env: Record<string, string>
  /** instance_settings rows (placement "settings"): written by `install profile apply` after `db migrate`. */
  settings: ConfigSetting[]
  /** Names of env vars / setting keys holding secrets (never print their values). */
  secretKeys: string[]
  /** Next steps a human or installer must do. */
  notes: string[]
}

/** Env vars that hold credentials (never logged). */
const SECRET_ENV = new Set([
  'ENCRYPTION_KEY', 'CRON_SECRET', 'WORKFLOW_SIGNING_SECRET', 'USERTASKS_SETUP_CODE', 'INSTANCE_ADMIN_TOKEN',
  'SUPABASE_SERVICE_ROLE_KEY', 'SUPABASE_JWT_SECRET', 'DATABASE_URL', 'MIGRATION_DATABASE_URL', 'REALTIME_DATABASE_URL', 'SCHEDULER_DATABASE_URL',
])

/** The connection string of a postgres database block. */
export function postgresUrl(db: Extract<Profile['database'], { provider: 'postgres' }>): string {
  let url = db.url
  if (!url) {
    const u = new URL('postgresql://placeholder')
    u.hostname = db.host!
    u.port = String(db.port ?? 5432)
    u.pathname = `/${encodeURIComponent(db.database!)}`
    u.username = encodeURIComponent(db.user!)
    if (db.password && db.auth === 'password') u.password = encodeURIComponent(db.password)
    url = u.toString()
  }
  const sslmode = db.sslmode ?? (['rds', 'azure', 'cloudsql'].includes(db.hosting) ? 'require' : undefined)
  if (sslmode && !/[?&]sslmode=/.test(url)) url += `${url.includes('?') ? '&' : '?'}sslmode=${sslmode}`
  return url
}

/**
 * Profile → environment variables and instance settings. Placement "env"
 * puts everything in the environment; "settings" moves the changeable areas
 * (SETTINGS_AREAS) into instance_settings so the setup wizard can change them.
 */
export function profileToConfig(profile: Profile): ProfileConfig {
  const env: Record<string, string> = {}
  const settings: ConfigSetting[] = []
  const notes: string[] = []
  const secretKeys = new Set<string>()
  const putEnv = (name: string, value: string | undefined, secret = false) => {
    if (value === undefined || value === '') return
    env[name] = value
    if (secret || SECRET_ENV.has(name)) secretKeys.add(name)
  }

  const { app } = profile
  putEnv('DEPLOYMENT_MODE', 'self_hosted')
  putEnv('APP_URL', app.url)
  putEnv('NEXT_PUBLIC_APP_URL', app.url)
  if (app.port) putEnv('APP_PORT', String(app.port))
  putEnv('ENCRYPTION_KEY', app.encryptionKey)
  putEnv('CRON_SECRET', app.cronSecret)
  putEnv('WORKFLOW_SIGNING_SECRET', app.signingSecret)
  putEnv('USERTASKS_SETUP_CODE', app.setupCode)
  putEnv('INSTANCE_ADMIN_TOKEN', app.instanceAdminToken)
  if (app.adminEmails.length) putEnv('INSTANCE_ADMIN_EMAILS', app.adminEmails.join(','))
  if (!app.encryptionKey) notes.push('ENCRYPTION_KEY is not set: run `write --generate-secrets` (credentials can\'t be stored encrypted without it)')

  if (profile.supabase && supabaseAreas(profile).length) {
    putEnv('SUPABASE_URL', profile.supabase.url)
    putEnv('NEXT_PUBLIC_SUPABASE_URL', profile.supabase.url)
    putEnv('SUPABASE_ANON_KEY', profile.supabase.anonKey)
    putEnv('NEXT_PUBLIC_SUPABASE_ANON_KEY', profile.supabase.anonKey)
    putEnv('SUPABASE_SERVICE_ROLE_KEY', profile.supabase.serviceRoleKey)
    putEnv('SUPABASE_JWT_SECRET', profile.supabase.jwtSecret)
  }

  const db = profile.database
  putEnv(PROVIDER_ENV.db, db.provider)
  if (db.provider === 'postgres') {
    const url = postgresUrl(db)
    const session = db.sessionUrl ?? url
    putEnv('DATABASE_URL', url)
    putEnv('MIGRATION_DATABASE_URL', session)
    putEnv('REALTIME_DATABASE_URL', session)
    putEnv('SCHEDULER_DATABASE_URL', session)
    if (db.auth !== 'password') putEnv('DATABASE_AUTH', db.auth)
    putEnv('DATABASE_AWS_REGION', db.awsRegion)
    putEnv('DATABASE_SSL_CA_FILE', db.caFile)
  } else {
    putEnv('DATABASE_URL', db.url)
  }

  const inSettings = (area: ProfileArea) => profile.placement === 'settings' && SETTINGS_AREAS.includes(area)
  for (const area of PROFILE_AREAS) {
    if (area === 'database') continue
    const providerArea = PROFILE_AREA_TO_PROVIDER[area]
    const block = profile[area] as { provider: string; options: Record<string, string> }
    const options: Record<string, string> = { ...block.options }
    if (area === 'auth' && profile.auth.sso.length) options.sso_providers = JSON.stringify(profile.auth.sso)
    const secretOptions = new Set(providerFields(providerArea, block.provider).filter((f) => f.secret).map((f) => f.option))
    if (area === 'auth') secretOptions.add('sso_providers')
    if (inSettings(area)) {
      settings.push({ key: `providers.${providerArea}`, value: block.provider, secret: false })
      for (const [option, value] of Object.entries(options)) {
        const secret = secretOptions.has(option) && !SECRET_REF.test(value)
        settings.push({ key: `${providerArea}.${option}`, value, secret })
        if (secret) secretKeys.add(`${providerArea}.${option}`)
      }
    } else {
      putEnv(PROVIDER_ENV[providerArea], block.provider)
      for (const [option, value] of Object.entries(options)) {
        const name = OPTION_ENV[providerArea]?.[option]
        if (!name) throw new Error(`no environment variable for ${providerArea}.${option}`)
        putEnv(name, value, secretOptions.has(option))
      }
    }
  }
  if (profile.placement === 'settings') {
    if (app.adminEmails.length) settings.push({ key: 'instance.admin_emails', value: app.adminEmails.join(','), secret: false })
    notes.push('After `usertasks-admin db migrate`, run `usertasks-admin install profile apply` to store the provider settings (the app falls back to defaults until then).')
  }

  if (profile.scheduler.provider === 'pg_cron') notes.push('pg_cron: install the jobs with `usertasks-admin switch scheduler --to pg_cron` once the app is reachable.')
  if (profile.scheduler.provider === 'external') notes.push(`External scheduler: call POST ${app.url}/api/cron/tick every minute with "Authorization: Bearer <CRON_SECRET>".`)
  if (profile.storage.provider === 'local') notes.push(`Files folder ${profile.storage.options.local_root}: must exist (or be creatable) and be writable by the app's service account, and be backed up with the database.`)
  if (profile.auth.ldap) notes.push('Directory (LDAP / AD): add the connection in Settings → Directory sync after setup (the profile does not store it in the environment).')
  for (const idp of profile.auth.sso) {
    notes.push(idp.type === 'oidc'
      ? `Register the redirect URI ${app.url}/auth/sso/${idp.id}/callback at ${idp.name ?? idp.id}.`
      : `Register ${app.url}/auth/saml/${idp.id}/metadata (ACS ${app.url}/auth/saml/${idp.id}/acs) at ${idp.name ?? idp.id}.`)
  }
  return { env, settings, secretKeys: [...secretKeys].sort(), notes }
}

