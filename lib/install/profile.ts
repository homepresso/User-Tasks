function randomHex(bytes: number): string {
  const buf = new Uint8Array(bytes)
  globalThis.crypto.getRandomValues(buf)
  return Array.from(buf, (b) => b.toString(16).padStart(2, '0')).join('')
}

const CODE_ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'
function randomSetupCode(): string {
  const buf = new Uint8Array(12)
  globalThis.crypto.getRandomValues(buf)
  const chars = Array.from(buf, (b) => CODE_ALPHABET[b % CODE_ALPHABET.length])
  return `${chars.slice(0, 4).join('')}-${chars.slice(4, 8).join('')}-${chars.slice(8).join('')}`
}

/** Env var → app field for the generated secrets. */
const GENERATED: Array<[keyof Profile['app'], string, () => string]> = [
  ['encryptionKey', 'ENCRYPTION_KEY', () => randomHex(32)],
  ['cronSecret', 'CRON_SECRET', () => randomHex(32)],
  ['signingSecret', 'WORKFLOW_SIGNING_SECRET', () => randomHex(32)],
  ['setupCode', 'USERTASKS_SETUP_CODE', randomSetupCode],
]

/**
 * Fill the instance secrets the profile doesn't give. Values from an existing
 * env file win over both the profile and generation: re-running an installer
 * must never replace ENCRYPTION_KEY (everything encrypted with it would be
 * lost). Returns the names that were generated.
 */
export function fillSecrets(profile: Profile, existingEnv: Record<string, string> = {}, opts: { generate: boolean } = { generate: true }): { profile: Profile; generated: string[]; kept: string[] } {
  const app = { ...profile.app }
  const generated: string[] = []
  const kept: string[] = []
  for (const [field, envName, make] of GENERATED) {
    const existing = existingEnv[envName]?.trim()
    if (existing) {
      if (app[field] && app[field] !== existing) kept.push(envName)
      ;(app as Record<string, unknown>)[field] = existing
    } else if (!app[field] && opts.generate) {
      ;(app as Record<string, unknown>)[field] = make()
      generated.push(envName)
    }
  }
  return { profile: { ...profile, app }, generated, kept }
}

/** Parse an env file (KEY=value lines; quotes stripped; comments ignored). */
export function parseEnvFile(text: string): Record<string, string> {
  const out: Record<string, string> = {}
  for (const line of text.split(/\r?\n/)) {
    const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line)
    if (!m) continue
    let value = m[2].trim()
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      const double = value.startsWith('"')
      value = value.slice(1, -1)
      if (double) value = value.replace(/\\(["\\nr])/g, (_, c: string) => (c === 'n' ? '\n' : c === 'r' ? '\r' : c))
    } else {
      value = value.replace(/\s+#.*$/, '')
    }
    out[m[1]] = value
  }
  return out
}

/**
 * Env file text. Values that need quoting are single-quoted (literal in
 * Docker Compose, systemd and shells: no `$` interpolation); a value holding
 * a single quote or a newline is double-quoted with \\ \" \n escapes.
 */
export function formatEnvFile(env: Record<string, string>, header?: string): string {
  const lines = header ? header.split('\n').map((l) => `# ${l}`) : []
  for (const [key, value] of Object.entries(env)) {
    const needsQuotes = /[\s#"'\\$`]/.test(value) || value === ''
    if (!needsQuotes) lines.push(`${key}=${value}`)
    else if (!/['\n\r]/.test(value)) lines.push(`${key}='${value}'`)
    else lines.push(`${key}="${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r')}"`)
  }
  return `${lines.join('\n')}\n`
}

const MASK = '********'

/** The profile with every credential replaced by ******** (safe to print or log). */
export function redactProfile(profile: Profile): Profile {
  const app = { ...profile.app }
  for (const field of ['encryptionKey', 'cronSecret', 'signingSecret', 'setupCode', 'instanceAdminToken'] as const) if (app[field]) app[field] = MASK
  const supabase = profile.supabase && { ...profile.supabase, serviceRoleKey: MASK, ...(profile.supabase.jwtSecret ? { jwtSecret: MASK } : {}) }
  const database = { ...profile.database } as Profile['database']
  if (database.provider === 'postgres') {
    if (database.password) database.password = MASK
    if (database.url) database.url = maskUrl(database.url)
    if (database.sessionUrl) database.sessionUrl = maskUrl(database.sessionUrl)
  } else if (database.url) database.url = maskUrl(database.url)
  const out = { ...profile, app, supabase, database } as Profile
  for (const area of PROFILE_AREAS) {
    if (area === 'database') continue
    const block = profile[area] as { provider: string; options: Record<string, string> }
    const secret = new Set(providerFields(PROFILE_AREA_TO_PROVIDER[area], block.provider).filter((f) => f.secret).map((f) => f.option))
    const options = Object.fromEntries(Object.entries(block.options).map(([k, v]) => [k, secret.has(k) && !SECRET_REF.test(v) ? MASK : v]))
    ;(out as unknown as Record<string, unknown>)[area] = { ...block, options }
  }
  out.auth = {
    ...out.auth,
    sso: profile.auth.sso.map((idp) => (idp.type === 'oidc' && idp.clientSecret && !SECRET_REF.test(idp.clientSecret) ? { ...idp, clientSecret: MASK } : idp)),
    ...(profile.auth.ldap ? { ldap: { ...profile.auth.ldap, ...(profile.auth.ldap.bindPassword ? { bindPassword: MASK } : {}) } } : {}),
  }
  return out
}

/** Env with secret values masked. */
export function redactEnv(config: ProfileConfig): Record<string, string> {
  return Object.fromEntries(Object.entries(config.env).map(([k, v]) => [k, config.secretKeys.includes(k) ? (/_URL$/.test(k) ? maskUrl(v) : MASK) : v]))
}

export function maskUrl(url: string): string {
  return url.replace(/(\/\/[^:/@]+:)[^@]*@/, `$1${MASK}@`)
}
